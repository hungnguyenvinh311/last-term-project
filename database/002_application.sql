CREATE TABLE IF NOT EXISTS Customer (
 customerID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 fullName VARCHAR(150) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 dateOfBirth DATE NULL, phoneNumber VARCHAR(30) NULL, shippingAddress VARCHAR(500) NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Accounts (
 accountID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 customerID INT UNSIGNED NOT NULL UNIQUE, email VARCHAR(254) NOT NULL UNIQUE,
 passwordHash VARCHAR(512) NOT NULL, role ENUM('customer','staff') NOT NULL DEFAULT 'customer',
 isActive BOOLEAN NOT NULL DEFAULT TRUE, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customerID) REFERENCES Customer(customerID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS AuthSessions (
 tokenHash CHAR(64) PRIMARY KEY, accountID INT UNSIGNED NOT NULL,
 expiresAt DATETIME NOT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(accountID) REFERENCES Accounts(accountID), INDEX(expiresAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Cart (
 cartID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, customerID INT UNSIGNED NOT NULL UNIQUE,
 createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customerID) REFERENCES Customer(customerID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CartItems (
 cartItemID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cartID INT UNSIGNED NOT NULL,
 articleID INT UNSIGNED NOT NULL, quantity INT NOT NULL,
 UNIQUE(cartID,articleID), CHECK(quantity>0 AND quantity<=99),
 FOREIGN KEY(cartID) REFERENCES Cart(cartID), FOREIGN KEY(articleID) REFERENCES Products(articleID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Orders (
 orderID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, customerID INT UNSIGNED NOT NULL,
 status VARCHAR(30) NOT NULL, paymentMethod VARCHAR(20) NOT NULL,
 itemSubTotal DECIMAL(18,2) NOT NULL, discountAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
 shippingFee DECIMAL(18,2) NOT NULL DEFAULT 0, totalAmount DECIMAL(18,2) NOT NULL,
 shippingAddress VARCHAR(500) NOT NULL, recipientPhone VARCHAR(30) NOT NULL,
 currency CHAR(3) NOT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 holdExpireAt DATETIME NULL, version INT NOT NULL DEFAULT 1,
 FOREIGN KEY(customerID) REFERENCES Customer(customerID), CHECK(totalAmount>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS OrderItems (
 orderItemID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, orderID INT UNSIGNED NOT NULL,
 articleID INT UNSIGNED NOT NULL, quantity INT NOT NULL, unitPrice DECIMAL(18,2) NOT NULL,
 productNameSnapshot VARCHAR(255) NOT NULL, specificationSnapshot JSON NULL, warrantySnapshot TEXT NULL,
 FOREIGN KEY(orderID) REFERENCES Orders(orderID), FOREIGN KEY(articleID) REFERENCES Products(articleID),
 CHECK(quantity>0 AND unitPrice>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Payments (
 paymentID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, orderID INT UNSIGNED NOT NULL UNIQUE,
 paymentMethod VARCHAR(20) NOT NULL, amount DECIMAL(18,2) NOT NULL, currency CHAR(3) NOT NULL,
 status VARCHAR(30) NOT NULL, transactionCode VARCHAR(100) NULL UNIQUE, paidAt DATETIME NULL,
 FOREIGN KEY(orderID) REFERENCES Orders(orderID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Shipments (
 shippingID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, orderID INT UNSIGNED NOT NULL UNIQUE,
 trackingNumber VARCHAR(100) NOT NULL UNIQUE, carrier VARCHAR(100) NOT NULL,
 status VARCHAR(30) NOT NULL, estimatedDeliveryDate DATETIME NULL, deliveredAt DATETIME NULL,
 FOREIGN KEY(orderID) REFERENCES Orders(orderID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS searchQueries (
 queryID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, customerID INT UNSIGNED NULL,
 queryType ENUM('text','voice','image') NOT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 searchCriteria JSON NOT NULL, FOREIGN KEY(customerID) REFERENCES Customer(customerID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS textQueries (
 queryID INT UNSIGNED PRIMARY KEY, queryText TEXT NOT NULL,
 FOREIGN KEY(queryID) REFERENCES searchQueries(queryID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS imageQueries (
 queryID INT UNSIGNED PRIMARY KEY, imageReference VARCHAR(500) NOT NULL, selectedRegion JSON NULL,
 FOREIGN KEY(queryID) REFERENCES searchQueries(queryID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS voiceQueries (
 queryID INT UNSIGNED PRIMARY KEY, audioReference VARCHAR(500) NULL, transcribedText TEXT NOT NULL,
 FOREIGN KEY(queryID) REFERENCES searchQueries(queryID)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS SearchResults (
 queryID INT UNSIGNED NOT NULL, articleID INT UNSIGNED NOT NULL, rankPosition INT NOT NULL, score DOUBLE NOT NULL,
 PRIMARY KEY(queryID,articleID), UNIQUE(queryID,rankPosition), CHECK(rankPosition>0),
 FOREIGN KEY(queryID) REFERENCES searchQueries(queryID), FOREIGN KEY(articleID) REFERENCES Products(articleID)
) ENGINE=InnoDB;
