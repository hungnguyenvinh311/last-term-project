from typing import Protocol

class AccountDAO(Protocol):
    def register(self, email: str, passwordHash: str, fullName: str, role="customer", phoneNumber=''): ...
    def findByEmail(self, email: str): ...
    def createSession(self, tokenHash: str, accountID: int, hours: int): ...
    def findSession(self, tokenHash: str): ...
    def deleteSession(self, tokenHash: str): ...
    def listAccounts(self): ...
    def setActive(self, accountID: int, active: bool, actorID: int): ...
    def setRole(self, accountID: int, role: str, actorID: int): ...
