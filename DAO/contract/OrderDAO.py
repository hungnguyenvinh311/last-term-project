from typing import Protocol

class OrderDAO(Protocol):
    def findById(self, orderID: int, connection=None): ...
    def findOwned(self, customerID: int, orderID: int): ...
    def createWithItems(self, customerID: int, payload: dict): ...
    def updateVersioned(self, orderID: int, status: str, version: int): ...
    def listOwned(self, customerID: int): ...
    def listAll(self): ...
    def cancel(self, customerID: int, orderID: int): ...
