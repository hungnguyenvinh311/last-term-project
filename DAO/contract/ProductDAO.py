from typing import Protocol

class ProductDAO(Protocol):
    def findById(self, articleID: int, connection=None): ...
    def findActive(self): ...
    def findAll(self): ...
    def save(self, values:dict, articleID:int|None=None): ...
    def findByCriteria(self, criteria): ...
    def findByRepresentation(self, criteria): ...
    def findAlternatives(self, source): ...
    def saveRepresentation(self, articleID: int, image, text): ...
