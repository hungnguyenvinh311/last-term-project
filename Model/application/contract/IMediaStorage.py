from typing import Protocol

class IMediaStorage(Protocol):
    def saveProductImage(self,content:bytes): ...
    def validateImage(self, content: bytes): ...
    def saveUpload(self, content: bytes, kind: str) -> str: ...
    def read(self, reference: str) -> bytes: ...
    def resolveProductImage(self, reference: str): ...
    def deleteExpiredQueryMedia(self, seconds=86400): ...
