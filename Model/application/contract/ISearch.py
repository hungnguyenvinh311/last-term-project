from typing import Protocol

class ISearch(Protocol):
    def searchText(self, text: str, contextKey: str, customerID=None, reset=False,brand=None,categoryID=None): ...
    def searchVoice(self, text: str, contextKey: str, customerID=None, reset=False,brand=None,categoryID=None): ...
    def searchImage(self, content: bytes, region=None, customerID=None,text='',brand=None,categoryID=None,imageCategoryID=None): ...
    def transcribeVoice(self, content: bytes, filename: str): ...
    def detectImageProducts(self, content: bytes): ...
