from typing import Protocol

class IAccount(Protocol):
    def register(self, email: str, password: str, fullName: str): ...
    def createStaff(self, email: str, password: str, fullName: str, role: str='Sales Staff'): ...
    def login(self, email: str, password: str): ...
    def authenticate(self, token: str): ...
    def logout(self, token: str): ...
    def profile(self, customerID: int): ...
    def updateProfile(self, customerID: int, values: dict): ...
    def listAccounts(self): ...
    def customerHistory(self, accountID: int): ...
    def setActive(self, accountID: int, active: bool, actorID: int): ...
    def setRole(self, accountID: int, role: str, actorID: int): ...
